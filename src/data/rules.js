// Built-in rules, shown on every device that has no local edits.
// Bump RULES_VERSION whenever DEFAULT_RULES changes: devices then drop their
// local edits so everyone ends up on the same published text.
//
// Format: "# " starts a section, "1. Title. Text" is a rule (renumbered
// automatically when displayed), anything else is a paragraph.
export const RULES_VERSION = 1;

export const DEFAULT_RULES = `# Our Purpose
We play to compete, build relationships, encourage one another, and honor God in how we treat others. Winning is fun. Fellowship is more important.

# Part 1: Our Standard
1. Have the best intentions. Help make this a good experience for everyone.
2. Assume the best intentions. Mistakes and missed calls happen. Give the benefit of the doubt.
3. Be honest. There are no referees. Do what is right even when nobody sees it.
4. Show respect. Compete hard without arguing, complaining, taunting, criticizing, or foul language. Encourage both teams.
5. Settle it peacefully. Pause and listen. If you can't agree, replay the possession. Never let a call damage a relationship.

# Part 2: Playing and Rotation
1. Eligibility. Players must be at least 16.
2. Rotation. Sign up and follow the order in the app. Winners stay up to the app's win limit. At the limit, both teams go to the back of the waitlist in shuffled order.
3. Courts. 5v5 is full court. 3v3 and 4v4 are half court.
4. Scoring. Baskets count 2 or 3. Both teams agree on a target score before the game starts. First team to the target wins, but must win by two.
5. First possession. A player shoots for it. Make: the shooter's team gets the ball. Miss: the other team does.
6. After a basket. The other team gets the ball, at the top of the key in half court or by inbounding in full court.
7. Substitutions. If a player is hurt or leaves, the next player in line steps in. If nobody is waiting, ask for a volunteer.

# Part 3: The Game
High-school rules apply except as changed here.
1. Fouls. Either player involved may call it; own your fouls. Call illegal contact that affects an opponent (pushing, holding, hitting, tripping). Play through incidental contact.
2. Foul calls. Call it right away, not after seeing whether the shot goes in. No free throws; the fouled player's team inbounds the ball. If the basket is made on the foul, it counts and the defense gets the ball as after any other basket.
3. Safety. No rough play, dangerous contact, or retaliation. Stop for injuries and give fallen players room.
4. Check ball. The defense checks the ball before play restarts, except on a full-court inbound after a basket.
5. Held ball. Teams alternate possession.
6. Screens. Set your feet. No moving screens.
7. Traveling. No more than two steps without dribbling. Once stopped, keep your pivot foot.
8. Double dribble. Don't dribble again after ending your dribble, or dribble with both hands at once.
9. Out of bounds. The line is out. The ball goes to the team that didn't touch it last.
10. Backboard. The backboard is in play, including the top edge if the ball doesn't go all the way over. A ball that goes over or behind it, or hits the supports, is out.
11. Goaltending. Don't touch a shot on its way down or a ball on the rim.
12. Clearing (half court). After a change of possession, the whole ball and at least one foot of the player with it must be beyond the 3-point line before a shot. Otherwise, no basket and the other team's ball. Offensive rebounds don't need clearing.
13. Three seconds. No offensive player may stay in the lane more than three seconds while their team has the ball in the frontcourt.
14. Backcourt (full court). Once in the frontcourt, the offense can't send the ball back and be first to touch it.
`;
